#!/usr/bin/env python3
"""Independent optional ADS-B velocity check; requires pyModeS 2.22.0.

The same three frames and expected fields are tested against the product in
tst_adsb_message. The first two were generated by OnAir encodeAirspeed; the
third is the published airborne ground-velocity example. No audio is opened.
"""
import math
import pyModeS as pms

cases = [
    ("8DABC1239B05001F682C008FDA25", (250, 90.0, -640, "IAS")),
    ("8DABC1239B05009F682C008E5F42", (250, 90.0, -640, "TAS")),
    ("8D485020994409940838175B284F", (159, 182.8803775528476, -832, "GS")),
]
for frame, expected in cases:
    assert pms.crc(frame) == 0
    result = pms.adsb.velocity(frame)
    assert result[0] == expected[0] and result[2:] == expected[2:]
    assert math.isclose(result[1], expected[1], abs_tol=0.01)
    corrupt = frame[:14] + ("0" if frame[14] != "0" else "1") + frame[15:]
    assert pms.crc(corrupt) != 0
print("PASS: independent pyModeS IAS, TAS, ground speed and CRC A/B")
